"""
Baseline trajectory estimators (all return p, q in the package convention,
i.e. canvas position of each frame's top-left corner, px).

  gm_sg               : GM tracking, the trajectory of the previous offline pipeline: in-frame GM position, jump
                        interpolation (|dGM| > 0.25 mm), Savitzky-Golay smoothing.
  live_col0           : online estimate, the trajectory computed in real time by the acquisition software and stored
                        with each clinical sweep (coords['col0_px']); in vivo only. Not reported in the paper.
  cf_imu              : complementary filter of the previous live system, which fuses the GM position with a
                        probe-orientation signal; in the paper it is evaluated in simulation only, with the
                        orientation signal generated by the simulator.
  seq_reg             : pairwise chaining of consecutive registrations of the unseparated frames (no graph).
  chain_same_frontend : Chaining*, pairwise chaining with the front end of the proposed method (no graph).
All trajectories are composited with the same compositor.
"""
import numpy as np
from scipy.signal import savgol_filter
from scipy.ndimage import gaussian_filter1d


def _sg(x):
    N = len(x)
    sg = max(7, min(int(N * 0.05) | 1, 51)); sg += (sg % 2 == 0)
    return savgol_filter(x, sg, min(3, sg - 2)) if N > sg else gaussian_filter1d(x, 12.0)


def gm_sg(coords, px_x, px_y):
    gx = np.array([c["gm_x_mm"] for c in coords], float)
    gy = np.array([c["gm_y_mm"] for c in coords], float)
    N = len(gx)
    out = np.zeros(N, bool); out[1:] = np.abs(np.diff(gx)) > 0.25
    if out.sum() and (~out).sum() > 2:
        t = np.arange(N); gx = np.interp(t, t[~out], gx[~out])
    return -_sg(gx) / px_x, -_sg(gy) / px_y


def live_col0(coords, px_y):
    p = np.array([c.get("col0_px", 0.0) for c in coords], float)
    gr = np.array([c.get("gm_row_frame", c.get("gm_y_mm", 0.0) / px_y) for c in coords], float)
    return p, -gr


def cf_imu(coords, px_x, px_y, tau=0.2, lam_mm_per_deg=0.12, sign=-1.0):
    gx = np.array([c["gm_x_mm"] for c in coords], float)
    gy = np.array([c["gm_y_mm"] for c in coords], float)
    qs = np.array([c.get("quality_score", 1.0) for c in coords], float)
    yaw = np.array([c.get("imu_yaw", 0.0) for c in coords], float)
    ts = np.array([c.get("ts", i / 12.0) for i, c in enumerate(coords)], float)
    # update rule of the complementary filter of the previous live system (orientation-difference branch)
    xf = np.zeros_like(gx); x_int = gx[0]; xf[0] = gx[0]
    for k in range(1, len(gx)):
        dt = max(ts[k] - ts[k - 1], 1e-4)
        dy = (yaw[k] - yaw[k - 1] + 180) % 360 - 180
        x_int += sign * dy * lam_mm_per_deg
        a0 = tau / (tau + dt)
        a = float(np.clip(a0 + (1 - a0) * (1 - qs[k] ** 2), 0, 1))
        xf[k] = a * x_int + (1 - a) * gx[k]
        x_int = 0.95 * x_int + 0.05 * xf[k]
    return -(xf - xf[0]) / px_x, -_sg(gy) / px_y


def seq_reg(pair_results, N):
    d = np.zeros((N, 2))
    ok = np.zeros(N, bool)
    for r in pair_results:
        if r.j == r.i + 1 and r.ok:
            d[r.j] = r.d; ok[r.j] = True
    return np.cumsum(d[:, 0]), np.cumsum(d[:, 1])


def chain_same_frontend(frames_raw, cfg, timestamps=None, return_pairs=False):
    """Controlled chaining baseline: pairwise chaining with the same front-end PROCEDURE as the proposed method
    (conditioning, layer separation, masks, lift-off detection, masked-NCC registration), but without the factor
    graph. Its registration inputs are not identical to those of the proposed method, because its refined layer is
    estimated from its own trajectory.

    * same conditioning, probe-fixed layer separation (B0, then one re-estimate from THIS baseline's own
      trajectory), static-pattern-weighted tissue masks and lift-off detection as `stitch_sweep`;
    * one full-search registration between consecutive *sighted* frames (the lag-1 pairs of the proposed
      method; across a lift-off this is the only gap-bridging pair);
    * positions are the cumulative sum of these displacements; a failed registration contributes zero motion;
      blind (lift-off) frames are placed by linear interpolation in time between the neighbouring sighted
      frames (they are not used for compositing).
    Returns p, q (px) and the blind mask."""
    from .pipeline import condition, initial_probe_fixed, detect_blind, register_all
    from .registration import estimate_speckle_area
    from . import preprocess as pp
    N = len(frames_raw)
    t = np.arange(N) / 12.0 if timestamps is None else np.asarray(timestamps, float)
    g, fs, ws = condition(frames_raw, cfg)
    spk = cfg.speckle_area_px or estimate_speckle_area(fs, ws)
    B = initial_probe_fixed(g) if cfg.layer_separation else np.zeros_like(g[0])
    spw = pp.static_pattern_weight(g, B) if cfg.layer_separation else 1.0
    fs_cur = [pp.smooth(np.maximum(x - B, 0), cfg.smooth_sigma) for x in g] if cfg.layer_separation else fs
    ws_cur = [w * spw for w in ws]
    blind = detect_blind(ws_cur)
    good = np.where(~blind)[0]

    last = []

    def chain(fs_, ws_):
        pairs = [(int(good[a]), int(good[a + 1])) for a in range(len(good) - 1)]
        res = register_all(fs_, ws_, cfg, pairs, spk)
        last[:] = res
        pg = np.zeros(len(good)); qg = np.zeros(len(good))
        for a, r in enumerate(res):
            d = r.d if r.ok else np.zeros(2)
            pg[a + 1] = pg[a] + d[0]; qg[a + 1] = qg[a] + d[1]
        p = np.interp(t, t[good], pg); q = np.interp(t, t[good], qg)
        return p, q

    p, q = chain(fs_cur, ws_cur)
    for _ in range(cfg.layer_iters if cfg.layer_separation else 0):
        B = pp.estimate_probe_fixed_layer(g, ws, p, q)
        spw = pp.static_pattern_weight(g, B)
        fs_cur = [pp.smooth(np.maximum(x - B, 0), cfg.smooth_sigma) for x in g]
        ws_cur = [w * spw for w in ws]
        p, q = chain(fs_cur, ws_cur)
    if return_pairs:
        return p - p[0], q - q[0], blind, list(last)
    return p - p[0], q - q[0], blind
